/**
 * Generates drizzle/0001_search_and_seed.sql: the FTS5 search table plus the rooms,
 * bookcases, sections, shelves and categories agreed in docs/PROJECT_BRIEF.md.
 *
 * IDs are deterministic (UUIDv5-style from a fixed key), so every phone seeds the
 * exact same rows and sync never sees duplicates. Re-run after editing LAYOUT:
 *   node scripts/build-seed-sql.mjs
 * Once a build with this migration has shipped, never edit it; add a new migration.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const NAMESPACE = 'maktabatna-seed-v1';
const SEED_TIME = 1790380800000; // 2026-09-26T00:00:00Z, same on every device

function uuid(key) {
  const h = createHash('sha1').update(`${NAMESPACE}:${key}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50; // version 5
  h[8] = (h[8] & 0x3f) | 0x80; // RFC 4122 variant
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);

const COMMON_COLS = ['id', 'created_at', 'updated_at'];
function insert(table, id, cols) {
  const names = [...COMMON_COLS, ...Object.keys(cols)];
  const values = [id, SEED_TIME, SEED_TIME, ...Object.values(cols)];
  return `INSERT INTO \`${table}\` (${names.map((n) => `\`${n}\``).join(', ')}) VALUES (${values.map(q).join(', ')});`;
}

/** Bookcases per room, numbered right to left. shelves = number of real shelves; every bookcase also gets a "top" surface. */
