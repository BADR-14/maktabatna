const CATEGORIES = [
  'تفسير وعلوم قرآن',
  'حديث وعلومه',
  'فقه وأصوله',
  'عقيدة',
  'سيرة وتراجم',
  'تاريخ',
  'لغة ونحو ومعاجم',
  'أدب',
  'رقائق وتزكية',
  'موسوعات',
  'عام',
];

// Comments ride along with the first statement: a comment-only chunk would be an empty statement.
const out = [
  [
    '-- Generated by scripts/build-seed-sql.mjs. Do not edit by hand.',
    '-- Full-text search over normalized title, people and publisher (text is normalized in JS before insert).',
    "CREATE VIRTUAL TABLE `books_fts` USING fts5(`book_id` UNINDEXED, `content`, tokenize = 'unicode61 remove_diacritics 2');",
  ].join('\n'),
];

LAYOUT.forEach((room, ri) => {
  const roomId = uuid(`room:${room.key}`);
  out.push(insert('rooms', roomId, { name: room.name, sort_order: ri + 1 }));
  room.bookcases.forEach((bc, bi) => {
    const n = bi + 1;
    const bcId = uuid(`bookcase:${room.key}:${n}`);
    out.push(insert('bookcases', bcId, { room_id: roomId, number: n, name: bc.name, kind: bc.kind, wall: bc.wall }));
    const secId = uuid(`section:${room.key}:${n}:1`);
    out.push(insert('sections', secId, { bookcase_id: bcId, number: 1 }));
    out.push(insert('shelves', uuid(`shelf:${room.key}:${n}:1:top`), { section_id: secId, number: 0, kind: 'top' }));
    for (let s = 1; s <= bc.shelves; s++) {
      out.push(insert('shelves', uuid(`shelf:${room.key}:${n}:1:${s}`), { section_id: secId, number: s, kind: 'shelf' }));
    }
  });
});

CATEGORIES.forEach((name, i) => out.push(insert('categories', uuid(`category:${name}`), { name, sort_order: i + 1 })));

const target = fileURLToPath(new URL('../drizzle/0001_search_and_seed.sql', import.meta.url));
writeFileSync(target, out.join('\n--> statement-breakpoint\n') + '\n');
console.log(`wrote ${out.length} statements to ${target}`);
